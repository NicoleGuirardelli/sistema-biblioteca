CREATE TABLE IF NOT EXISTS usuario (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    matricula VARCHAR(30) NOT NULL UNIQUE,
    perfil VARCHAR(20) NOT NULL CHECK (perfil IN ('ALUNO', 'BIBLIOTECARIO')),
    ativo BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS livro (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    isbn VARCHAR(20) UNIQUE,
    categoria VARCHAR(80),
    qtd_total INTEGER NOT NULL,
    qtd_disponivel INTEGER NOT NULL,
    CHECK (qtd_disponivel >= 0 AND qtd_disponivel <= qtd_total)
);

CREATE TABLE IF NOT EXISTS emprestimo (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL,
    livro_id INTEGER NOT NULL,
    data_emprestimo DATE NOT NULL,
    data_prevista DATE NOT NULL,
    data_devolucao DATE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('ATIVO', 'ENCERRADO')),
    em_atraso BOOLEAN NOT NULL,
    CONSTRAINT fk_emprestimo_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT fk_emprestimo_livro FOREIGN KEY (livro_id) REFERENCES livro (id),
    CHECK (status <> 'ATIVO' OR data_devolucao IS NULL)
);
